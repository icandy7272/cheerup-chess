const mirror=s=>String.fromCharCode(104-(s.charCodeAt(0)-97))+s[1];
function make(chapter,variant,pieces,moves,answers,question,hints,explanation){
 const flip=variant>=3;const sq=s=>flip?mirror(s):s;const c=new Chess();c.clear();
 for(const [s,p]of Object.entries(pieces))c.put({type:p.toLowerCase(),color:p===p.toUpperCase()?'w':'b'},sq(s));
 const fen=c.fen();const line=moves.map(([a,b,p])=>c.move({from:sq(a),to:sq(b),promotion:p||'q'}).san);
 const labels=['认识妙招','换个出发点','再找一次','镜子里的妙招','换边试一试','我会自己找'];
 return {id:`original-${chapter}-${variant+1}`,chapter,title:labels[variant],fen,lines:[line],question:question.replace(/\b[a-h][1-8]\b/g,sq),answers:answers.map(sq),hints:hints.map(t=>t.replace(/\b[a-h][1-8]\b/g,sq)),explanation:explanation.replace(/\b[a-h][1-8]\b/g,sq),source:'CheerUp Chess 原创 · 同主题变式练习',bookRef:''};
}
